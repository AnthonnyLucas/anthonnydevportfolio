test('tecnologias vinculadas apenas ao projeto selecionado, com múltiplos IDs e atualização dinâmica',async()=>{
  reset();
  const initial=await call(techEndpoint,'technologies');
  const python=initial.body.technologies.find(t=>t.label==='Python');
  const java=initial.body.technologies.find(t=>t.label==='Java');
  assert.ok(python&&java);
  let created=await call(projectEndpoint,'projects','POST',{title:'Projeto AQUA',description:'Demonstração',categories:['iot'],technologyIds:[python.id,java.id,python.id]},true);
  assert.equal(created.status,200,JSON.stringify(created.body));
  const project=created.body.projects[0];
  assert.deepEqual(project.technologyIds,[python.id,java.id]);
  assert.deepEqual(project.technologies.map(t=>t.label),['Python','Java']);
  assert.equal(created.body.projects.find(p=>p.id==='seed-smart-solar-home').technologies.length,0);
  let dynamic=await call(techEndpoint,'technologies','POST',{label:'Angular Avançado',cat:'frameworks',icon:'A',color:'#f34455'},true);
  assert.equal(dynamic.status,200);
  const added=dynamic.body.technologies.find(t=>t.label==='Angular Avançado');
  created=await call(projectEndpoint,'projects','POST',{id:project.id,title:'Projeto AQUA',description:'Demonstração',categories:['iot'],technologyIds:[python.id,added.id]},true);
  assert.equal(created.status,200,JSON.stringify(created.body));
  assert.deepEqual(created.body.projects[0].technologies.map(t=>t.label),['Python','Angular Avançado']);
  dynamic=await call(techEndpoint,'technologies','POST',{...added,label:'Angular 21'},true);
  assert.equal(dynamic.status,200);
  const refreshed=await call(projectEndpoint,'projects');
  assert.deepEqual(refreshed.body.projects[0].technologies.map(t=>t.label),['Python','Angular 21']);
  assert.deepEqual(refreshed.body.projects[0].technologyIds,[python.id,added.id]);
  dynamic=await call(techEndpoint,'technologies','DELETE',{id:added.id},true);
  assert.equal(dynamic.status,200);
  const afterDelete=await call(projectEndpoint,'projects');
  assert.equal(afterDelete.body.projects[0].technologies.at(-1).label,'Angular Avançado','snapshot preserva histórico no registro vinculado');
  const updated=await call(projectEndpoint,'projects','POST',{id:project.id,title:'Projeto AQUA',description:'Demonstração',categories:['iot'],technologyIds:[python.id,added.id]},true);
  assert.equal(updated.status,200,JSON.stringify(updated.body));
  assert.equal(updated.body.projects[0].technologies.length,2);
});
test('IDs inexistentes não podem ser associados; tags antigos são preservados e nomes conhecidos são reconhecidos',async()=>{
  reset();
  await getStore('portfolio-projects').setJSON('projects',[{id:'legacy',title:'Legado',description:'Antigo',category:'Dados',tags:['Python','Pandas','Automação']}]);
  const existing=await call(projectEndpoint,'projects');
  assert.deepEqual(existing.body.projects[0].technologies.map(t=>t.label),['Python']);
  assert.deepEqual(existing.body.projects[0].tags,['Python','Pandas','Automação']);
  assert.deepEqual(existing.body.projects[0].topics,['Pandas','Automação']);
  let response=await call(projectEndpoint,'projects','POST',{id:'legacy',title:'Legado',description:'Antigo',categories:['dados'],technologyIds:['fake-id']},true);
  assert.equal(response.status,400);
  response=await call(projectEndpoint,'projects','POST',{id:'legacy',title:'Legado',description:'Antigo',categories:['dados']},true);
  assert.equal(response.status,200,JSON.stringify(response.body));
  assert.deepEqual(response.body.projects[0].technologies.map(t=>t.label),['Python']);
  assert.deepEqual(response.body.projects[0].tags,['Python','Pandas','Automação']);
  assert.deepEqual(response.body.projects[0].topics,['Pandas','Automação']);
  response=await call(projectEndpoint,'projects','POST',{id:'legacy',title:'Legado',description:'Antigo',categories:['dados'],technologyIds:[]},true);
  assert.equal(response.status,200);
  assert.deepEqual(response.body.projects[0].technologies,[],'lista vazia explícita deve remover os vínculos');
});
